void init_board_eval(SimdBoard& board) {
    board.mg_pst_score = 0;
    board.eg_pst_score = 0;
    board.game_phase = 0;
    for (int sq = 0; sq < 64; sq++) {
        uint8_t piece = board.squares[sq];
        if (piece != EMPTY_SQUARE) {
            int type = piece & 0x0F;
            int phase_val = 0;
            if (type == KNIGHT || type == BISHOP) phase_val = 1;
            else if (type == ROOK) phase_val = 2;
            else if (type == QUEEN) phase_val = 4;
            board.game_phase += phase_val;

            int flipped_sq = (piece & BLACK) ? sq : (sq ^ 56);
            int mg_val = MG_PST[type][flipped_sq];
            int eg_val = EG_PST[type][flipped_sq];

            if (piece & BLACK) {
                board.mg_pst_score -= mg_val;
                board.eg_pst_score -= eg_val;
            } else {
                board.mg_pst_score += mg_val;
                board.eg_pst_score += eg_val;
            }
        }
    }
    if (board.game_phase > 24) board.game_phase = 24;
    board.init_nnue();
}

void init_evaluate() {
    alignas(64) uint8_t table[64] = {0};
    for(int i=0; i<64; i++) {
        int type = i % 16;
        if (type == PAWN) table[i] = 1;
        else if (type == KNIGHT || type == BISHOP) table[i] = 3;
        else if (type == ROOK) table[i] = 5;
        else if (type == QUEEN) table[i] = 9;
        else if (type == KING) table[i] = 100;
        else table[i] = 0;
    }
    piece_value_table = _mm512_load_si512(table);
}

int evaluate(const SimdBoard& board, int side_to_move) {
    int score = nnue::evaluate(board.white_acc, board.black_acc, side_to_move);
    return score;
}

void evaluate_batch(const SimdBoard* boards, const int* side_to_move, int* scores) {
    for(int i=0; i<8; i++) {
        scores[i] = evaluate(boards[i], side_to_move[i]);
    }
}

